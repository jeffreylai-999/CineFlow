CREATE TABLE CREDITCARD
(
    CARD_ID VARCHAR(10) PRIMARY KEY NOT NULL,
    CARD_NO BIGINT NOT NULL,
    CARD_HOLD_NAME VARCHAR(50) NOT NULL,
    CARD_TYPE VARCHAR(20) NOT NULL,
    CARD_BANK VARCHAR(30) NOT NULL,
    CARD_EXP VARCHAR(11) NOT NULL
);
CREATE TABLE CUSTOMER
(
    CUS_ID VARCHAR(10) PRIMARY KEY NOT NULL,
    CUS_NAME VARCHAR(50) NOT NULL,
    CUS_GENDER VARCHAR(6) NOT NULL,
    CUS_BIRTHDAY VARCHAR(11) NOT NULL,
    CUS_IC VARCHAR(15) NOT NULL,
    CUS_PHONE VARCHAR(12) NOT NULL,
    CUS_ADDRESS VARCHAR(50) NOT NULL,
    CUS_EMAIL VARCHAR(50) NOT NULL
);
CREATE TABLE STAFF
(
    STAFF_ID VARCHAR(10) PRIMARY KEY NOT NULL,
    STAFF_NAME VARCHAR(50) NOT NULL,
    STAFF_POSITION VARCHAR(20) NOT NULL,
    STAFF_PASSWORD VARCHAR(30) NOT NULL,
    STAFF_GENDER VARCHAR(6) NOT NULL,
    STAFF_BIRTHDAY VARCHAR(11) NOT NULL,
    STAFF_IC VARCHAR(15) NOT NULL,
    STAFF_PHONE VARCHAR(12) NOT NULL,
    STAFF_ADDRESS VARCHAR(50) NOT NULL,
    STAFF_EMAIL VARCHAR(50) NOT NULL,
    STAFF_STATUS VARCHAR(10) NOT NULL,
    STAFF_QUESTION INT NOT NULL,
    STAFF_ANSWER VARCHAR(50) NOT NULL
);
CREATE TABLE HALL
(
    HALL_ID VARCHAR(10) PRIMARY KEY NOT NULL,
    HALL_LOCATION VARCHAR(30) NOT NULL,
    HALL_STATUS VARCHAR(15),
    HALL_PERIOD VARCHAR(11)
);
CREATE TABLE MOVIE
(
    MOVIE_ID VARCHAR(10) PRIMARY KEY NOT NULL,
    MOVIE_NAME VARCHAR(50) NOT NULL,
    MOVIE_PRICE VARCHAR(7) NOT NULL,
    RUNNING_TIME VARCHAR(4) NOT NULL,
    MOVIE_GENRE VARCHAR(20) NOT NULL,
    RELEASE_DATE VARCHAR(11) NOT NULL,
    OFFLINE_DATE VARCHAR(11) NOT NULL,
    HALL_ID VARCHAR(10) NOT NULL,
    FOREIGN KEY (HALL_ID) REFERENCES HALL (HALL_ID) ON DELETE CASCADE
);
CREATE TABLE SHOWTIME
(
    SHOW_ID VARCHAR(10) PRIMARY KEY NOT NULL,
    SHOW_DATE VARCHAR(11) NOT NULL,
    SHOW_TIME VARCHAR(6) NOT NULL,
    MOVIE_ID VARCHAR(10) NOT NULL,
    FOREIGN KEY (MOVIE_ID) REFERENCES MOVIE (MOVIE_ID) ON DELETE CASCADE
);
CREATE TABLE PAYMENT
(
    PAYMENT_ID VARCHAR(10) PRIMARY KEY NOT NULL,
    STAFF_ID VARCHAR(10) NOT NULL,
    SHOW_ID VARCHAR(10) NOT NULL,
    CUS_TYPE VARCHAR(15) NOT NULL,
    ADULT INT NOT NULL,
    CHILD INT NOT NULL,
    SEAT_NO VARCHAR(255) NOT NULL,
    TOTAL_PRICE DECIMAL(6) NOT NULL,
    RESERVATION_ID VARCHAR(10),
    CUS_ID VARCHAR(10),
    PAYMENT_TYPE VARCHAR(15),
    CARD_ID VARCHAR(10),
    PAYMENT_DATE VARCHAR(11),
    FOREIGN KEY (STAFF_ID) REFERENCES STAFF (STAFF_ID) ON DELETE CASCADE,
    FOREIGN KEY (SHOW_ID) REFERENCES SHOWTIME (SHOW_ID) ON DELETE CASCADE,
    FOREIGN KEY (CUS_ID) REFERENCES CUSTOMER (CUS_ID) ON DELETE CASCADE,
    FOREIGN KEY (CARD_ID) REFERENCES CREDITCARD (CARD_ID) ON DELETE CASCADE
);
CREATE TABLE PROMOTION
(
    PROMOTION_ID VARCHAR(10) PRIMARY KEY NOT NULL,
    PROMOTION_START VARCHAR(11) NOT NULL,
    PROMOTION_END VARCHAR(11) NOT NULL,
    PROMOTION_DISCOUNT INT NOT NULL,
    MOVIE_ID VARCHAR(10) NOT NULL,
    FOREIGN KEY (MOVIE_ID) REFERENCES MOVIE (MOVIE_ID) ON DELETE CASCADE
);
CREATE TABLE TICKET
(
    TICKET_ID VARCHAR(10) PRIMARY KEY NOT NULL,
    SEAT_NO VARCHAR(10) NOT NULL,
    TICKET_TYPE VARCHAR(10) NOT NULL,
    TICKET_PRICE VARCHAR(10) NOT NULL,
    GOODS_SERVICE_TAX VARCHAR(10) NOT NULL,
    ENTERTAINMENT_TAX VARCHAR(10) NOT NULL,
    PAYMENT_ID VARCHAR(10) NOT NULL,
    FOREIGN KEY (PAYMENT_ID) REFERENCES PAYMENT (PAYMENT_ID) ON DELETE CASCADE
);

